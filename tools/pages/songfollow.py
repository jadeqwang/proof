#!/usr/bin/env python3
"""Song follow: a sticky player bar that plays the song and walks a review page with it.

The component is tools/pages/songfollow.js + songfollow.css (no dependencies). The song's sections and timed lyric
lines come from analysis/m2sm/song_map.md and are written to tools/pages/song_m2sm.js (regenerated whenever the map is
newer). A page opts in by giving each card a song time and including the snippet this file makes:

    <div class="card" data-t="2:42.0" data-t-end="2:43.2"> ... <span class="t">2:42.0</span> ... </div>

  data-t       start on the -2sm master, seconds (162.0) or m:ss(.s) ("2:42.0"); a range "2:42.0-2:43.2" also works
  data-t-end   optional end
  cards without data-t are "untimed": never highlighted (the page should group them at the end; see groupUntimed)
  the card's time label (default selector '.t') becomes a "play from here" link; a card with no label gets a chip

Usage
    python3 tools/pages/songfollow.py inject media/decisions.html     (re)insert the player block before </body>
    python3 tools/pages/songfollow.py data                             regenerate tools/pages/song_m2sm.js
    python3 tools/pages/songfollow.py time B2_face [WL_top ...]        a shot's -2sm time, from the keyframe picks
From Python (page builders):
    sys.path.insert(0, "<repo>/tools/pages"); import songfollow
    html = songfollow.inject(html, "/abs/path/of/the/page.html", cards=".card")

All paths in the snippet are relative to the page, so it works from file:// (the song is inputs/Proof (-2sm).mp3;
no copy of the audio is made). The block sits between <!-- songfollow:begin --> and <!-- songfollow:end -->, so
re-injecting replaces it.
"""
import json
import os
import re
import sys
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SONG_MAP = os.path.join(ROOT, "analysis", "m2sm", "song_map.md")
DATA_JS = os.path.join(HERE, "song_m2sm.js")
MP3 = os.path.join(ROOT, "inputs", "Proof (-2sm).mp3")
DURATION = 268.40
BEGIN, END = "<!-- songfollow:begin -->", "<!-- songfollow:end -->"


def _num(cell):
    m = re.match(r"\s*\**\s*([\d.]+)", cell)
    return float(m.group(1)) if m else None


def _kind(name):
    n = name.lower()
    for k in ("pre-chorus", "post-chorus", "chorus", "verse", "bridge", "intro", "outro", "coda", "final", "stop",
              "interlude", "break"):
        if k in n:
            return {"post-chorus": "tail", "final": "coda"}.get(k, k)
    return "other"


def _short(name):
    s = re.sub(r"\s*\([^)]*\)", "", name).split(" — ")[0].strip()
    return s.replace("Instrumental break", "Piano break").replace("Post-chorus tail", "Tail")


def song_data():
    """song_map.md -> {duration, sections: [{t, end, name, short, kind}], lyrics: [{t, end, text}]}."""
    sections, lyrics, part = [], [], None
    for ln in open(SONG_MAP, encoding="utf-8"):
        if ln.startswith("## "):
            part = ln[3:].strip()
            continue
        if not ln.startswith("|"):
            continue
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if part and part.startswith("2.") and len(cells) >= 4 and re.fullmatch(r"\d+", cells[0]):
            t, e = _num(cells[2]), _num(cells[3])
            if t is not None and e is not None:
                sections.append({"t": t, "end": e, "name": cells[1], "short": _short(cells[1]), "kind": _kind(cells[1])})
        elif part and part.startswith("3.") and len(cells) >= 3 and re.fullmatch(r"[\d.]+", cells[0]):
            text = re.sub(r"\*\*", "", cells[2]).strip()
            lyrics.append({"t": float(cells[0]), "end": float(cells[1]), "text": text})
    if not sections or not lyrics:
        raise SystemExit(f"songfollow: could not read sections/lyrics from {SONG_MAP} (table format changed?)")
    return {"duration": DURATION, "source": "analysis/m2sm/song_map.md", "sections": sections, "lyrics": lyrics}


def write_data(force=False):
    if not force and os.path.exists(DATA_JS) and os.path.getmtime(DATA_JS) >= os.path.getmtime(SONG_MAP):
        return DATA_JS
    d = song_data()
    with open(DATA_JS, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/pages/songfollow.py from analysis/m2sm/song_map.md; do not edit.\n")
        f.write("window.SONG_M2SM = " + json.dumps(d, ensure_ascii=False, indent=0) + ";\n")
    return DATA_JS


def _rel(target, page_dir):
    return urllib.parse.quote(os.path.relpath(target, page_dir).replace(os.sep, "/"))


def snippet(page_path, cards=".card", time_label=".t", group_untimed=False, key=None):
    """The <link>/<script> block for a page at page_path (absolute or repo-relative)."""
    write_data()
    page_dir = os.path.dirname(os.path.join(ROOT, page_path))
    opts = {"audio": _rel(MP3, page_dir), "cards": cards, "timeLabel": time_label, "groupUntimed": group_untimed}
    if key:
        opts["key"] = key
    return "\n".join([
        BEGIN,
        f'<link rel="stylesheet" href="{_rel(os.path.join(HERE, "songfollow.css"), page_dir)}">',
        f'<script src="{_rel(DATA_JS, page_dir)}"></script>',
        f'<script src="{_rel(os.path.join(HERE, "songfollow.js"), page_dir)}"></script>',
        f"<script>SongFollow.init({json.dumps(opts)});</script>",
        END,
    ])


def inject(html, page_path, **opts):
    """Insert (or replace) the songfollow block just before </body>."""
    html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", html, flags=re.S)
    i = html.lower().rfind("</body>")
    if i < 0:
        raise SystemExit("songfollow.inject: no </body> in the page")
    return html[:i] + snippet(page_path, **opts) + "\n" + html[i:]


def shot_time(sid):
    """A shot id -> (label, source) from the newest keyframe picks (r4, then r3) or footage_slots. Local only."""
    kf = os.path.join(ROOT, "media", "keyframes")
    slots = os.path.join(kf, "r3", "footage_slots.json")
    if os.path.exists(slots):
        s = json.load(open(slots)).get("shots", {}).get(sid)
        if s:
            return s["song_time"], "media/keyframes/r3/footage_slots.json"
    for rnd in ("r4", "r3"):
        d = os.path.join(kf, rnd)
        if not os.path.isdir(d):
            continue
        for st in sorted(os.listdir(d)):
            p = os.path.join(d, st, "picks.json")
            if os.path.exists(p):
                pk = json.load(open(p)).get(sid)
                if pk and pk.get("time"):
                    return pk["time"], os.path.relpath(p, ROOT)
    return None, "not found in media/keyframes/r4|r3/*/picks.json; look in layout/sets/<set>/shots.js (check its clock)"


def main(argv):
    if len(argv) >= 2 and argv[0] == "inject":
        for p in argv[1:]:
            ap = os.path.abspath(p)
            html = open(ap, encoding="utf-8").read()
            open(ap, "w", encoding="utf-8").write(inject(html, ap))
            print(f"songfollow: injected into {os.path.relpath(ap, ROOT)}")
    elif argv[:1] == ["data"]:
        print("wrote", os.path.relpath(write_data(force=True), ROOT))
    elif len(argv) >= 2 and argv[0] == "time":
        for sid in argv[1:]:
            t, src = shot_time(sid)
            print(f"{sid}: {t or '(none)'}  [{src}]")
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
