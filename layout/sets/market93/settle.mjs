// Settle the grandmother's cart and its groceries with Rapier (r5, 2026-11-26; Jade: objects obey physics, checked with an
// existing engine, never hand-placed). Not hand-rolled physics: @dimforge/rapier3d-compat, as holdcheck and mv10/settle.mjs.
//   node layout/sets/market93/settle.mjs      -> writes layout/sets/market93/settled.js (poses in the cart's own frame)
// 1. The cart (props/shopping_cart, "Carro De La Compra" by alexvladimircm, CC BY 4.0) as ONE dynamic convex hull, dropped
//    2 cm onto the floor: it lands on its four casters; the settled lift and tilt say whether the model stands level.
// 2. The cart model as a static trimesh (in its settled pose); a carton (cuboid) and a melon (ball) dropped into the basket
//    one after the other; 4 s of 1/120 s steps, friction 0.8. Final poses written out.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const RAPIER = require(process.env.RAPIER_DIR || '/home/jade/Documents/layout-deps/node_modules/@dimforge/rapier3d-compat');
await RAPIER.init();
const ROOT = new URL('../../', import.meta.url).pathname;
function glb(path) {
  const f = fs.readFileSync(path); let o = 12; const ch = [];
  while (o < f.length) { const cl = f.readUInt32LE(o); ch.push(f.subarray(o + 8, o + 8 + cl)); o += 8 + cl; }
  const J = JSON.parse(ch[0].toString()), B = ch[1], pos = [], idx = [];
  const acc = (i, T, n) => { const a = J.accessors[i], bv = J.bufferViews[a.bufferView], off = B.byteOffset + (bv.byteOffset || 0) + (a.byteOffset || 0);
    return new T(B.buffer.slice(off, off + a.count * n * T.BYTES_PER_ELEMENT)); };
  for (const m of J.meshes) for (const p of m.primitives) { const P = acc(p.attributes.POSITION, Float32Array, 3), base = pos.length / 3; pos.push(...P);
    if (p.indices != null) { const a = J.accessors[p.indices]; const I = acc(p.indices, a.componentType === 5125 ? Uint32Array : Uint16Array, 1); for (const i of I) idx.push(base + i); }
    else for (let i = 0; i < P.length / 3; i++) idx.push(base + i); }
  return { pos: Float32Array.from(pos), idx: Uint32Array.from(idx) };
}
const CART = glb(ROOT + 'assets/props/shopping_cart/shopping_cart.glb');
const r4 = (x) => +x.toFixed(4);
// 1. the cart on the floor
const w1 = new RAPIER.World({ x: 0, y: -9.81, z: 0 }); w1.timestep = 1 / 120;
w1.createCollider(RAPIER.ColliderDesc.cuboid(3, 0.05, 3).setTranslation(0, -0.05, 0).setFriction(0.8), w1.createRigidBody(RAPIER.RigidBodyDesc.fixed()));
const cb = w1.createRigidBody(RAPIER.RigidBodyDesc.dynamic().setTranslation(0, 0.02, 0).setLinearDamping(0.5).setAngularDamping(0.8));
w1.createCollider(RAPIER.ColliderDesc.convexHull(CART.pos).setDensity(300).setFriction(0.8).setRestitution(0.02), cb);
for (let s = 0; s < 480; s++) w1.step();
const ct = cb.translation(), cr = cb.rotation();
const tiltDeg = 2 * Math.asin(Math.min(1, Math.hypot(cr.x, cr.z))) * 180 / Math.PI;
const cart = { lift: r4(ct.y), drift: [r4(ct.x), r4(ct.z)], tilt_deg: +tiltDeg.toFixed(3), speed: r4(Math.hypot(...Object.values(cb.linvel()))) };
// 2. the groceries in the basket (cart static at its settled height; it settles level, so its frame = the model frame + lift)
const w2 = new RAPIER.World({ x: 0, y: -9.81, z: 0 }); w2.timestep = 1 / 120;
w2.createCollider(RAPIER.ColliderDesc.trimesh(CART.pos, CART.idx).setFriction(0.8), w2.createRigidBody(RAPIER.RigidBodyDesc.fixed()));
const CARTON = [0.30, 0.16, 0.22], MELON_R = 0.09;   // a carton of groceries and a honeydew, as in the hand-built cart
const items = [
  { kind: 'carton', desc: RAPIER.ColliderDesc.cuboid(CARTON[0] / 2, CARTON[1] / 2, CARTON[2] / 2), drop: [0.02, 0.62, -0.1], yaw: 12 },
  { kind: 'melon', desc: RAPIER.ColliderDesc.ball(MELON_R), drop: [-0.05, 0.66, 0.2], yaw: 0 },
];
const bodies = items.map((it) => { const y = it.yaw * Math.PI / 360;
  const b = w2.createRigidBody(RAPIER.RigidBodyDesc.dynamic().setTranslation(...it.drop).setRotation({ x: 0, y: Math.sin(y), z: 0, w: Math.cos(y) }).setLinearDamping(0.5).setAngularDamping(0.8).setCcdEnabled(true));
  w2.createCollider(it.desc.setDensity(400).setFriction(0.8).setRestitution(0.05), b); for (let s = 0; s < 120; s++) w2.step(); return b; });
for (let s = 0; s < 480; s++) w2.step();
const OUT = { note: 'settled by layout/sets/market93/settle.mjs (Rapier): the cart model on the floor; the groceries in its basket, in the cart model frame (origin on the floor under the basket centre, nose +z)',
  cart, CARTON, MELON_R,
  items: bodies.map((b, n) => { const t = b.translation(), r = b.rotation(); return { kind: items[n].kind, at: [t.x, t.y, t.z].map(r4), quat: [r.x, r.y, r.z, r.w].map((x) => +x.toFixed(5)), speed: r4(Math.hypot(...Object.values(b.linvel()))) }; }) };
fs.writeFileSync(new URL('./settled.js', import.meta.url), '// GENERATED by settle.mjs (Rapier); do not edit by hand\nexport const SETTLED = ' + JSON.stringify(OUT, null, 1) + ';\n');
